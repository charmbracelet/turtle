// setConversions builds the translation table of the copy and the record
// delimiters conv=block and conv=unblock use.
func (e *engine) setConversions() {
	conv := e.op.conv
	for i := range e.table {
		e.table[i] = byte(i)
	}
	if conv.has(convASCII) {
		e.applyTable(ebcdicToASCII)
		e.translate = true
	}
	if conv.has(convUcase) {
		for i := range e.table {
			e.table[i] = upper(e.table[i])
		}
		e.translate = true
	} else if conv.has(convLcase) {
		for i := range e.table {
			e.table[i] = lower(e.table[i])
		}
		e.translate = true
	}
	if conv.has(convEBCDIC) {
		e.applyTable(asciiToEbcdic)
		e.translate = true
	} else if conv.has(convIBM) {
		e.applyTable(asciiToIBM)
		e.translate = true
	}

	e.newline, e.space = '\n', ' '
	if conv.has(convEBCDIC) {
		e.newline, e.space = asciiToEbcdic['\n'], asciiToEbcdic[' ']
	} else if conv.has(convIBM) {
		e.newline, e.space = asciiToIBM['\n'], asciiToIBM[' ']
	}
}

// applyTable composes table into the translation table of the copy.
func (e *engine) applyTable(table [256]byte) {
	for i := range e.table {
		e.table[i] = table[e.table[i]]
	}
}

func upper(c byte) byte {
	if 'a' <= c && c <= 'z' {
		return c - 'a' + 'A'
	}
	return c
}

func lower(c byte) byte {
	if 'A' <= c && c <= 'Z' {
		return c - 'A' + 'a'
	}
	return c
}

// process runs one converted input block through the conversion pipeline
// and aggregates it into the output blocks. swab comes first, as the
// processing order the GNU manual gives numbers it before the remaining
// conversions.
func (e *engine) process(data []byte) error {
	if e.op.conv.has(convSwab) {
		data = e.swab(data)
	}
	if e.translate {
		for i, c := range data {
			data[i] = e.table[c]
		}
	}
	switch {
	case e.op.conv.has(convBlock):
		return e.convertBlock(data)
	case e.op.conv.has(convUnblock):
		return e.convertUnblock(data)
	default:
		return e.convertSimple(data)
	}
}

// swab swaps every pair of bytes, holding the last one back to pair with
// the first byte of the next block when the input is odd.
func (e *engine) swab(data []byte) []byte {
	if len(data) == 0 {
		return data
	}
	s := e.sbuf[:len(data)+1]
	copy(s, data)
	n := len(data)
	prev := e.saved
	if (prev < 0) == (n%2 == 1) {
		e.saved = int(s[n-1])
		n--
	} else {
		e.saved = -1
	}
	for i := n; 1 < i; i -= 2 {
		s[i] = s[i-2]
	}
	if prev < 0 {
		return s[1 : n+1]
	}
	s[1] = byte(prev)
	return s[:n+1]
}

// convertBlock converts newline-terminated records into fixed cbs-sized
// ones, padding short records with spaces and counting each overlong
// record once, at its first excess byte.
func (e *engine) convertBlock(data []byte) error {
	for _, c := range data {
		if c == e.newline {
			for ; e.col < e.op.cbs; e.col++ {
				if err := e.outputByte(e.space); err != nil {
					return err
				}
			}
			e.col = 0
			e.overlong = false
		} else {
			if e.col < e.op.cbs {
				if err := e.outputByte(c); err != nil {
					return err
				}
			} else if !e.overlong {
				e.truncated++
				e.overlong = true
			}
			e.col++
		}
	}
	return nil
}

// convertUnblock converts fixed cbs-sized records into newline-terminated
// ones, deleting the trailing spaces and counting none of them.
func (e *engine) convertUnblock(data []byte) error {
	for i := 0; i < len(data); {
		c := data[i]
		if e.col >= e.op.cbs {
			e.col, e.pending = 0, 0
			if err := e.outputByte(e.newline); err != nil {
				return err
			}
			continue
		}
		e.col++
		i++
		if c == e.space {
			e.pending++
			continue
		}
		for ; e.pending > 0; e.pending-- {
			if err := e.outputByte(e.space); err != nil {
				return err
			}
		}
		if err := e.outputByte(c); err != nil {
			return err
		}
	}
	return nil
}
