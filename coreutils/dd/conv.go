package dd

// convSet is the set of conversions the conv= operand asks for.
type convSet uint32

const (
	convASCII convSet = 1 << iota
	convEBCDIC
	convIBM
	convBlock
	convUnblock
	convLcase
	convUcase
	convSwab
	convNoerror
	convNotrunc
	convSync
	convExcl
	convNocreat
	convFsync
)

func (c convSet) has(f convSet) bool { return c&f != 0 }

func (c convSet) hasAny(f ...convSet) bool {
	for _, g := range f {
		if c&g != 0 {
			return true
		}
	}
	return false
}

